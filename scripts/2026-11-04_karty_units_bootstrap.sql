-- 2026-11-04 — Karty Yolu geçişi: puan bantları geçici ünitelere dönüşür.
--
-- Ünite içerikleri (konular, adlar) sonra belirlenecek. O zamana kadar her
-- ayrı `min_score` bandı bir ünite olur; bugünkü öğrenme sırası korunur
-- (0 bandı → Ünite 1, 100 bandı → Ünite 2). Kartlar bant içinde eklenme
-- (`karty_id`) sırasıyla dizilir.
--
-- İdempotent: üniteler zaten varsa yeniden açılmaz, ünitesi olan karta
-- dokunulmaz, hiçbir satır silinmez. Adları sonradan değiştirmek için:
-- PUT ll-api/karty/admin/units/{sequence}.

BEGIN;

-- Şema (KartyUnitSchemaHelper ile aynı DDL).
CREATE TABLE IF NOT EXISTS karty_unit (
    karty_unit_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sequence integer NOT NULL,
    title text NOT NULL,
    emblem_karty_id integer NULL REFERENCES karty (karty_id) ON DELETE SET NULL,
    created_date timestamp with time zone NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS ix_karty_unit_sequence ON karty_unit (sequence);
ALTER TABLE karty ADD COLUMN IF NOT EXISTS unit_id integer NULL
    REFERENCES karty_unit (karty_unit_id) ON DELETE SET NULL;
ALTER TABLE karty ADD COLUMN IF NOT EXISTS unit_order integer NULL;
CREATE INDEX IF NOT EXISTS ix_karty_unit_id_unit_order ON karty (unit_id, unit_order);

-- Her bant için bir ünite (yalnız hiç ünite yokken).
INSERT INTO karty_unit (sequence, title, created_date)
SELECT band.sequence,
       CASE band.sequence
           WHEN 1 THEN 'İlk kelimeler'
           WHEN 2 THEN 'Yeni kelimeler'
           ELSE 'Ünite ' || band.sequence
       END,
       now()
FROM (
    SELECT dense_rank() OVER (ORDER BY min_score) AS sequence
    FROM (SELECT DISTINCT min_score FROM karty) AS scores
) AS band
WHERE NOT EXISTS (SELECT 1 FROM karty_unit);

-- Ünitesiz kartlar bantlarının ünitesine, eklenme sırasıyla.
WITH bands AS (
    SELECT min_score, dense_rank() OVER (ORDER BY min_score) AS sequence
    FROM (SELECT DISTINCT min_score FROM karty) AS scores
),
ranked AS (
    SELECT k.karty_id,
           b.sequence,
           row_number() OVER (PARTITION BY k.min_score ORDER BY k.karty_id) AS position
    FROM karty k
    JOIN bands b ON b.min_score = k.min_score
    WHERE k.unit_id IS NULL
)
UPDATE karty k
SET unit_id = u.karty_unit_id,
    unit_order = r.position + COALESCE(
        (SELECT max(x.unit_order) FROM karty x WHERE x.unit_id = u.karty_unit_id), 0)
FROM ranked r
JOIN karty_unit u ON u.sequence = r.sequence
WHERE k.karty_id = r.karty_id;

-- Başlık görseli: ünitede "Haus" varsa o (Karty Yolu taslağındaki ev),
-- yoksa ünitenin ilk kartı.
UPDATE karty_unit u
SET emblem_karty_id = COALESCE(
    (SELECT k.karty_id FROM karty k
     WHERE k.unit_id = u.karty_unit_id AND lower(k.noun_text) = 'haus'
     LIMIT 1),
    (SELECT k.karty_id FROM karty k
     WHERE k.unit_id = u.karty_unit_id
     ORDER BY k.unit_order, k.karty_id
     LIMIT 1))
WHERE u.emblem_karty_id IS NULL;

COMMIT;
