using Microsoft.EntityFrameworkCore;
using Postgres;

namespace Service.Helpers;

/// <summary>
/// <c>karty_unit</c> tablosunu ve <c>karty.unit_id</c> / <c>karty.unit_order</c>
/// kolonlarını garanti eder.
///
/// Depodaki desen (<see cref="KartyAudioSchemaHelper"/>): idempotent DDL,
/// **veriye dokunmaz**. Mevcut kartların ünitelere atanması bir kerelik
/// geçiş işi; okuma yolunda değil, depodaki
/// <c>scripts/2026-11-04_karty_units_bootstrap.sql</c> ile yapılır.
///
/// <see cref="KartyLearningSchemaHelper"/> bunu çağırır: <c>Karty</c>
/// satırını tam yükleyen her sorgu yeni kolonları da okuduğu için kolonların
/// "kart öğrenme şeması hazır" ile aynı anda var olması gerekiyor.
/// </summary>
public static class KartyUnitSchemaHelper
{
    private static readonly SemaphoreSlim SchemaLock = new(1, 1);
    private static bool _isReady;

    public static async Task EnsureCreatedAsync(
        LingualLoopContext context,
        CancellationToken cancellationToken)
    {
        if (_isReady) return;

        await SchemaLock.WaitAsync(cancellationToken);
        try
        {
            if (_isReady) return;

            await context.Database.ExecuteSqlRawAsync(
                """
                CREATE TABLE IF NOT EXISTS karty_unit (
                    karty_unit_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    sequence integer NOT NULL,
                    title text NOT NULL,
                    emblem_karty_id integer NULL REFERENCES karty (karty_id) ON DELETE SET NULL,
                    created_date timestamp with time zone NOT NULL DEFAULT now()
                );

                CREATE UNIQUE INDEX IF NOT EXISTS ix_karty_unit_sequence
                    ON karty_unit (sequence);

                ALTER TABLE karty ADD COLUMN IF NOT EXISTS unit_id integer NULL
                    REFERENCES karty_unit (karty_unit_id) ON DELETE SET NULL;
                ALTER TABLE karty ADD COLUMN IF NOT EXISTS unit_order integer NULL;

                CREATE INDEX IF NOT EXISTS ix_karty_unit_id_unit_order
                    ON karty (unit_id, unit_order);
                """,
                cancellationToken);

            _isReady = true;
        }
        finally
        {
            SchemaLock.Release();
        }
    }
}
