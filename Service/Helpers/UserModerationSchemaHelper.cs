using Microsoft.EntityFrameworkCore;
using Postgres;

namespace Service.Helpers;

/// Engelleme ve bildirim tabloları. Kullanıcı silinince satırları da silinir
/// (AspNetUsers'a CASCADE).
public static class UserModerationSchemaHelper
{
    private static readonly SemaphoreSlim SchemaLock = new(1, 1);
    private static bool _isReady;

    public static async Task EnsureCreatedAsync(
        StelindaContext context,
        CancellationToken cancellationToken)
    {
        if (_isReady) return;

        await SchemaLock.WaitAsync(cancellationToken);
        try
        {
            if (_isReady) return;

            await context.Database.ExecuteSqlRawAsync(
                """
                CREATE TABLE IF NOT EXISTS user_block (
                    user_block_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    blocker_id text NOT NULL REFERENCES "AspNetUsers"("Id") ON DELETE CASCADE,
                    blocked_id text NOT NULL REFERENCES "AspNetUsers"("Id") ON DELETE CASCADE,
                    created_at timestamp with time zone NOT NULL
                );

                CREATE UNIQUE INDEX IF NOT EXISTS ix_user_block_pair
                    ON user_block (blocker_id, blocked_id);

                CREATE INDEX IF NOT EXISTS ix_user_block_blocked
                    ON user_block (blocked_id);

                CREATE TABLE IF NOT EXISTS user_report (
                    user_report_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    reporter_id text NOT NULL REFERENCES "AspNetUsers"("Id") ON DELETE CASCADE,
                    reported_id text NOT NULL REFERENCES "AspNetUsers"("Id") ON DELETE CASCADE,
                    reason text NOT NULL,
                    context text NOT NULL,
                    created_at timestamp with time zone NOT NULL,
                    resolved_at timestamp with time zone NULL
                );

                CREATE INDEX IF NOT EXISTS ix_user_report_reported
                    ON user_report (reported_id);
                """,
                cancellationToken);

            _isReady = true;
        }
        finally
        {
            SchemaLock.Release();
        }
    }

    /// Kullanıcının görmemesi gerekenler: engelledikleri ve onu engelleyenler.
    public static async Task<HashSet<string>> HiddenUserIdsAsync(
        StelindaContext context,
        string userId,
        CancellationToken cancellationToken)
    {
        await EnsureCreatedAsync(context, cancellationToken);

        var ids = await context.UserBlocks
            .AsNoTracking()
            .Where(b => b.BlockerId == userId || b.BlockedId == userId)
            .Select(b => b.BlockerId == userId ? b.BlockedId : b.BlockerId)
            .ToListAsync(cancellationToken);

        return ids.ToHashSet();
    }
}
